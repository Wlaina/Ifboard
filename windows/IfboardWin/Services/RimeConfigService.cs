using System.IO;
using System.Text;
using IfboardWin.Models;

namespace IfboardWin.Services;

public static class RimeConfigService
{
    public static RimePreferences LoadPreferences()
    {
        var prefs = new RimePreferences();

        if (File.Exists(Paths.DefaultCustomYaml))
        {
            var lines = File.ReadAllLines(Paths.DefaultCustomYaml, Encoding.UTF8);
            var schemas = new List<string>();
            bool inSchemaList = false;
            foreach (var raw in lines)
            {
                var line = raw.Trim();
                if (line.StartsWith("schema_list:", StringComparison.OrdinalIgnoreCase))
                {
                    inSchemaList = true;
                    continue;
                }
                if (inSchemaList)
                {
                    if (line.StartsWith("- schema:", StringComparison.OrdinalIgnoreCase))
                    {
                        var id = line["- schema:".Length..].Split('#')[0].Trim();
                        if (!string.IsNullOrEmpty(id)) schemas.Add(id);
                        continue;
                    }
                    if (!string.IsNullOrEmpty(line) && !line.StartsWith("#"))
                        inSchemaList = false;
                }

                if (line.StartsWith("menu/page_size:", StringComparison.OrdinalIgnoreCase) &&
                    int.TryParse(line["menu/page_size:".Length..].Split('#')[0].Trim(), out var ps))
                {
                    prefs.PageSize = Math.Clamp(ps, 5, 9);
                }
                else if (line.Contains("Shift_L: noop", StringComparison.Ordinal))
                {
                    prefs.CtrlSpaceOnlySwitch = true;
                }
                else if (line.Contains("accept: Tab, send: Page_Down", StringComparison.Ordinal))
                {
                    prefs.TabPageFlip = true;
                }
            }

            if (schemas.Count > 0)
            {
                prefs.PrimarySchema = schemas[0] == "double_pinyin_flypy" ? "double_pinyin_flypy" : "rime_ice";
                prefs.KeepBothSchemas = schemas.Contains("rime_ice") && schemas.Contains("double_pinyin_flypy");
            }
        }

        var primaryCustomYaml = prefs.PrimarySchema == "rime_ice"
            ? Paths.RimeIceCustomYaml
            : Paths.FlypyCustomYaml;
        var fallbackCustomYaml = prefs.PrimarySchema == "rime_ice"
            ? Paths.FlypyCustomYaml
            : Paths.RimeIceCustomYaml;
        var activeYaml = File.Exists(primaryCustomYaml)
            ? primaryCustomYaml
            : (File.Exists(fallbackCustomYaml) ? fallbackCustomYaml : null);

        if (activeYaml != null)
        {
            var txt = File.ReadAllText(activeYaml, Encoding.UTF8);
            prefs.FuzzyEnEng = txt.Contains("derive/eng$/en/", StringComparison.Ordinal);
            prefs.FuzzyInIng = txt.Contains("derive/ing$/in/", StringComparison.Ordinal);
            prefs.FuzzyZhChSh = txt.Contains("derive/^([zcs])h/$1/", StringComparison.Ordinal);
            prefs.GrammarEnabled = txt.Contains("language: wanxiang-lts-zh-hans", StringComparison.Ordinal);
        }

        if (File.Exists(Paths.FlypyCustomYaml))
        {
            var flypyTxt = File.ReadAllText(Paths.FlypyCustomYaml, Encoding.UTF8);
            prefs.KeepRawFlypyPreedit = flypyTxt.Contains("translator/preedit_format:", StringComparison.Ordinal);
        }

        return prefs;
    }

    public static void ApplyPreferences(RimePreferences prefs)
    {
        Directory.CreateDirectory(Paths.RimeUserDir);
        EnsureCustomPhrasePlaceholders();
        WriteDefaultCustomYaml(prefs);
        PatchDefaultYamlTabBinding(prefs.TabPageFlip);
        WriteRimeIceCustomYaml(prefs);
        WriteFlypyCustomYaml(prefs);
    }

    public static void EnsureCustomPhrasePlaceholders()
    {
        foreach (var fileName in new[] { "custom_phrase.txt", "custom_phrase_double.txt" })
        {
            var p = Path.Combine(Paths.RimeUserDir, fileName);
            if (!File.Exists(p))
            {
                File.WriteAllText(
                    p,
                    "# Rime table\n# encoding: utf-8\n# 格式：词条<Tab>编码<Tab>权重（可自行追加常用短语）\n",
                    new UTF8Encoding(false)
                );
            }
        }
    }

    private static void WriteDefaultCustomYaml(RimePreferences prefs)
    {
        var secondary = prefs.PrimarySchema == "rime_ice" ? "double_pinyin_flypy" : "rime_ice";
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Ifboard Desktop");
        sb.AppendLine("patch:");
        sb.AppendLine("  schema_list:");
        sb.AppendLine($"    - schema: {prefs.PrimarySchema}");
        if (prefs.KeepBothSchemas)
            sb.AppendLine($"    - schema: {secondary}");
        sb.AppendLine();
        sb.AppendLine($"  menu/page_size: {Math.Clamp(prefs.PageSize, 5, 9)}");
        sb.AppendLine();

        if (prefs.CtrlSpaceOnlySwitch)
        {
            sb.AppendLine("  # 屏蔽单按 Shift / Ctrl 误触切换中英，统一使用 Ctrl+Space");
            sb.AppendLine("  ascii_composer:");
            sb.AppendLine("    good_old_caps_lock: true");
            sb.AppendLine("    switch_key:");
            sb.AppendLine("      Caps_Lock: noop");
            sb.AppendLine("      Shift_L: noop");
            sb.AppendLine("      Shift_R: noop");
            sb.AppendLine("      Control_L: noop");
            sb.AppendLine("      Control_R: noop");
            sb.AppendLine();
        }

        sb.AppendLine("  key_binder/bindings/+:");
        if (prefs.CtrlSpaceOnlySwitch)
            sb.AppendLine("    - { when: always, accept: Control+space, toggle: ascii_mode }");
        sb.AppendLine("    - { when: always, accept: Control+Shift+F, toggle: traditionalization }");
        sb.AppendLine("    - { when: always, accept: Control+Shift+f, toggle: traditionalization }");
        sb.AppendLine("    - { when: always, accept: Control+period, toggle: ascii_punct }");
        if (prefs.TabPageFlip)
        {
            sb.AppendLine("    - { when: has_menu, accept: Tab, send: Page_Down }");
            sb.AppendLine("    - { when: has_menu, accept: Shift+Tab, send: Page_Up }");
        }
        sb.AppendLine("    - { when: paging, accept: comma, send: Page_Up }");
        sb.AppendLine("    - { when: has_menu, accept: period, send: Page_Down }");

        File.WriteAllText(Paths.DefaultCustomYaml, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>
    /// 雾凇默认 default.yaml 中 { when: composing, accept: Tab, send: Shift+Right } 会先拦截 Tab 键，
    /// 当用户开启「Tab / Shift+Tab 翻页」时需注释掉该规则以避免吞掉翻页事件。
    /// </summary>
    public static void PatchDefaultYamlTabBinding(bool enableTabFlip)
    {
        if (!File.Exists(Paths.DefaultYaml)) return;
        var content = File.ReadAllText(Paths.DefaultYaml, Encoding.UTF8);
        const string activeRule = "- { when: composing, accept: Tab, send: Shift+Right }";
        const string commentedRule = "# - { when: composing, accept: Tab, send: Shift+Right }  # disabled by Ifboard Tab paging";

        if (enableTabFlip && content.Contains(activeRule, StringComparison.Ordinal) &&
            !content.Contains(commentedRule, StringComparison.Ordinal))
        {
            content = content.Replace(activeRule, commentedRule, StringComparison.Ordinal);
            File.WriteAllText(Paths.DefaultYaml, content, new UTF8Encoding(false));
        }
        else if (!enableTabFlip && content.Contains(commentedRule, StringComparison.Ordinal))
        {
            content = content.Replace(commentedRule, activeRule, StringComparison.Ordinal);
            File.WriteAllText(Paths.DefaultYaml, content, new UTF8Encoding(false));
        }
    }

    private static void WriteRimeIceCustomYaml(RimePreferences prefs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Ifboard Desktop");
        sb.AppendLine("patch:");
        AppendIconPatchIfPresent(sb);

        if (prefs.GrammarEnabled)
            AppendGrammarPatch(sb);

        if (prefs.FuzzyEnEng || prefs.FuzzyInIng || prefs.FuzzyZhChSh)
        {
            sb.AppendLine("  speller/algebra/+:");
            if (prefs.FuzzyZhChSh)
            {
                sb.AppendLine("    - derive/^([zcs])h/$1/");
                sb.AppendLine("    - derive/^([zcs])([^h])/$1h$2/");
            }
            if (prefs.FuzzyEnEng)
            {
                sb.AppendLine("    - derive/eng$/en/");
                sb.AppendLine("    - derive/en$/eng/");
            }
            if (prefs.FuzzyInIng)
            {
                sb.AppendLine("    - derive/ing$/in/");
                sb.AppendLine("    - derive/in$/ing/");
            }
        }

        File.WriteAllText(Paths.RimeIceCustomYaml, sb.ToString(), new UTF8Encoding(false));
    }

    private static void WriteFlypyCustomYaml(RimePreferences prefs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Ifboard Desktop");
        sb.AppendLine("patch:");
        AppendIconPatchIfPresent(sb);

        if (prefs.GrammarEnabled)
            AppendGrammarPatch(sb);

        sb.AppendLine("  switches:");
        sb.AppendLine("    - name: ascii_mode");
        sb.AppendLine("      states: [ 中, Ａ ]");
        sb.AppendLine("      reset: 0");
        sb.AppendLine("    - name: ascii_punct");
        sb.AppendLine("      states: [ ¥, $ ]");
        sb.AppendLine("      reset: 1");
        sb.AppendLine("    - name: traditionalization");
        sb.AppendLine("      states: [ 简, 繁 ]");
        sb.AppendLine("    - name: emoji");
        sb.AppendLine("      states: [ 💀, 😄 ]");
        sb.AppendLine("      reset: 1");
        sb.AppendLine("    - name: full_shape");
        sb.AppendLine("      states: [ 半角, 全角 ]");
        sb.AppendLine("    - name: search_single_char");
        sb.AppendLine("      states: [正常, 单字]");
        sb.AppendLine("      abbrev: [词, 单]");
        sb.AppendLine();

        if (prefs.KeepRawFlypyPreedit)
        {
            sb.AppendLine("  # 保持输入栏显示紧凑双拼编码而非展开为全拼");
            sb.AppendLine("  translator/preedit_format:");
            sb.AppendLine("    - xform/(?<=[A-Z])\\s(?=[A-Z])//");
            sb.AppendLine();
        }

        sb.AppendLine("  speller/algebra:");
        sb.AppendLine("    - erase/^xx$/");
        if (prefs.FuzzyZhChSh)
        {
            sb.AppendLine("    - derive/^([zcs])h/$1/");
            sb.AppendLine("    - derive/^([zcs])([^h])/$1h$2/");
        }
        if (prefs.FuzzyEnEng)
        {
            sb.AppendLine("    - derive/eng$/en/");
            sb.AppendLine("    - derive/en$/eng/");
        }
        if (prefs.FuzzyInIng)
        {
            sb.AppendLine("    - derive/ing$/in/");
            sb.AppendLine("    - derive/in$/ing/");
        }
        sb.AppendLine("    - derive/^([jqxy])u$/$1v/");
        sb.AppendLine("    - derive/^([aoe])([ioun])$/$1$1$2/");
        sb.AppendLine("    - xform/^([aoe])(ng)?$/$1$1$2/");
        sb.AppendLine("    - xform/iu$/Ⓠ/");
        sb.AppendLine("    - xform/(.)ei$/$1Ⓦ/");
        sb.AppendLine("    - xform/uan$/Ⓡ/");
        sb.AppendLine("    - xform/[uv]e$/Ⓣ/");
        sb.AppendLine("    - xform/un$/Ⓨ/");
        sb.AppendLine("    - xform/^sh/Ⓤ/");
        sb.AppendLine("    - xform/^ch/Ⓘ/");
        sb.AppendLine("    - xform/^zh/Ⓥ/");
        sb.AppendLine("    - xform/uo$/Ⓞ/");
        sb.AppendLine("    - xform/ie$/Ⓟ/");
        sb.AppendLine("    - xform/(.)i?ong$/$1Ⓢ/");
        sb.AppendLine("    - xform/ing$|uai$/Ⓚ/");
        sb.AppendLine("    - xform/(.)ai$/$1Ⓓ/");
        sb.AppendLine("    - xform/(.)en$/$1Ⓕ/");
        sb.AppendLine("    - xform/(.)eng$/$1Ⓖ/");
        sb.AppendLine("    - xform/[iu]ang$/Ⓛ/");
        sb.AppendLine("    - xform/(.)ang$/$1Ⓗ/");
        sb.AppendLine("    - xform/ian$/Ⓜ/");
        sb.AppendLine("    - xform/(.)an$/$1Ⓙ/");
        sb.AppendLine("    - xform/(.)ou$/$1Ⓩ/");
        sb.AppendLine("    - xform/[iu]a$/Ⓧ/");
        sb.AppendLine("    - xform/iao$/Ⓝ/");
        sb.AppendLine("    - xform/(.)ao$/$1Ⓒ/");
        sb.AppendLine("    - xform/ui$/Ⓥ/");
        sb.AppendLine("    - xform/in$/Ⓑ/");
        sb.AppendLine("    - xlit/ⓆⓌⓇⓉⓎⓊⒾⓄⓅⓈⒹⒻⒼⒽⒿⓀⓁⓏⓍⒸⓋⒷⓃⓂ/qwrtyuiopsdfghjklzxcvbnm/");

        File.WriteAllText(Paths.FlypyCustomYaml, sb.ToString(), new UTF8Encoding(false));
    }

    private static void AppendIconPatchIfPresent(StringBuilder sb)
    {
        if (!File.Exists(Path.Combine(Paths.RimeUserDir, "icons", "cn.ico"))) return;
        sb.AppendLine("  schema/icon: \"icons/cn.ico\"");
        sb.AppendLine("  schema/zhung_icon: \"icons/cn.ico\"");
        sb.AppendLine("  schema/ascii_icon: \"icons/en.ico\"");
        sb.AppendLine("  schema/half_icon: \"icons/half.ico\"");
        sb.AppendLine("  schema/full_icon: \"icons/full.ico\"");
        sb.AppendLine();
    }

    private static void AppendGrammarPatch(StringBuilder sb)
    {
        sb.AppendLine("  grammar:");
        sb.AppendLine("    language: wanxiang-lts-zh-hans");
        sb.AppendLine("    collocation_max_length: 6");
        sb.AppendLine("    collocation_min_length: 3");
        sb.AppendLine("    collocation_penalty: -14");
        sb.AppendLine("    non_collocation_penalty: -6");
        sb.AppendLine("    weak_collocation_penalty: -100");
        sb.AppendLine("    rear_penalty: -20");
        sb.AppendLine("  translator/contextual_suggestions: false");
        sb.AppendLine("  translator/max_homophones: 8");
        sb.AppendLine();
    }
}
