namespace IfboardWin.Services;

/// <summary>
/// 打拼音时的 Ctrl+A / Ctrl+Z：
///   · 第一次 Ctrl+A 只全选这串拼音（不交给应用），再按退格 / Delete 一次删光，直接打字母则替换掉它；
///   · 已选中拼音时再按一次 Ctrl+A，清掉拼音并交给应用做正常的全选；
///   · Ctrl+Z 撤回正在输入的拼音，候选窗一起关掉（原先应用撤回了文字，候选窗却还留着）。
/// </summary>
internal static class SelectAllLua
{
    public const string FileName = "ifb_select_all.lua";
    public const string Processor = "lua_processor@*ifb_select_all";
    /// <summary>插在第 2 个处理器之前：在 key_binder / speller / 编辑器之前拿到按键，又不和自动空格的「@before 0」重名</summary>
    public const string PatchLine = "  engine/processors/@before 1: " + Processor;

    /// <summary>选中时把拼音字母显示成反色方块的过滤器（改写候选的预编辑文字，内嵌拼音跟着变）</summary>
    public const string FilterFileName = "ifb_select_all_filter.lua";
    public const string Filter = "lua_filter@*ifb_select_all_filter";
    public const string FilterPatchLine = "  engine/filters/+: [ " + Filter + " ]";

    public const string FilterSource = """
-- Generated by Ifboard Desktop
-- 打拼音时按 Ctrl+A 全选后，拼音字母显示成反色方块（🅽🅸 🅷🅰🅾），一眼看出整串已选中；
-- 选中状态由 ifb_select_all 处理器写在 context 属性里。只改显示，上屏和按键不受影响。
local BASE = 0x1F170          -- NEGATIVE SQUARED LATIN CAPITAL LETTER A
local VS15 = utf8.char(0xFE0E) -- A/B/O/P 有彩色表情版本，加文字样式选择符强制按普通文字显示
local EMOJI_LIKE = { [0x41] = true, [0x42] = true, [0x4F] = true, [0x50] = true }

local function boxed(text)
  local out = {}
  for _, c in utf8.codes(text) do
    local up = (c >= 0x61 and c <= 0x7A) and (c - 32) or c
    if up >= 0x41 and up <= 0x5A then
      out[#out + 1] = utf8.char(BASE + up - 0x41)
      if EMOJI_LIKE[up] then out[#out + 1] = VS15 end
    else
      out[#out + 1] = utf8.char(c)
    end
  end
  return table.concat(out)
end

local function filter(input, env)
  local selected = env.engine.context:get_property("ifb_select_all") == "1"
  for cand in input:iter() do
    if selected then
      local p = cand.preedit
      if p ~= nil and p ~= "" then
        cand.preedit = boxed(p)
      end
    end
    yield(cand)
  end
end

return filter
""";

    public const string Source = """
-- Generated by Ifboard Desktop
-- 打拼音时的 Ctrl+A / Ctrl+Z：
--   · 第一次 Ctrl+A 只全选这串拼音（不交给应用：应用全选会连同拼音一起选中，有的应用还会把拼音清掉）；
--     选中后按退格或 Delete 一次删光，直接打字母则先清掉再重新输入，按其他键取消选中；
--   · 已选中拼音时再按一次 Ctrl+A，清掉拼音并交给应用做正常的全选（之后一次退格删掉全部文字）；
--   · Ctrl+Z 撤回正在输入的拼音，候选窗一起关掉。
local kAccepted, kNoop = 1, 2

local function is_modifier(r)
  return r:find("^Shift_") or r:find("^Control_") or r:find("^Alt_") or r:find("^Meta_")
    or r:find("^Super_") or r:find("^Hyper_") or r == "Caps_Lock"
end

-- 选中状态写进 context 属性，再刷新组字，让 ifb_select_all_filter 把拼音显示成反色方块
local function set_selected(env, ctx, on)
  env.selected = on
  local want = on and "1" or ""
  if ctx:get_property("ifb_select_all") ~= want then
    ctx:set_property("ifb_select_all", want)
    if ctx:is_composing() then ctx:refresh_non_confirmed_composition() end
  end
end

local function init(env)
  env.selected = false
end

local function func(key, env)
  local ctx = env.engine.context
  if key:release() then return kNoop end
  if not ctx:is_composing() then
    if env.selected then set_selected(env, ctx, false) end
    return kNoop
  end

  local code = key.keycode
  local plain_ctrl = key:ctrl() and not key:alt() and not key:shift()

  if plain_ctrl and (code == 0x61 or code == 0x41) then
    if env.selected then
      -- 第二次 Ctrl+A：先清掉正在输入的拼音，再交给应用全选——
      -- 否则拼音还在组字状态，应用选中后按退格仍由输入法一个字母一个字母删
      set_selected(env, ctx, false)
      ctx:clear()
      return kNoop
    end
    set_selected(env, ctx, true)
    return kAccepted
  end

  if plain_ctrl and (code == 0x7a or code == 0x5a) then
    set_selected(env, ctx, false)
    ctx:clear()
    return kAccepted
  end

  if not env.selected then return kNoop end

  local r = key:repr()
  if is_modifier(r) then return kNoop end

  set_selected(env, ctx, false)
  if r == "BackSpace" or r == "Delete" or r == "Control+BackSpace" or r == "Control+Delete"
      or r == "KP_Delete" then
    ctx:clear()
    return kAccepted
  end
  -- 像普通文本框一样：选中状态下直接打字母 = 替换掉选中的拼音
  if not key:ctrl() and not key:alt() and ((code >= 0x61 and code <= 0x7a) or (code >= 0x41 and code <= 0x5a)) then
    ctx:clear()
  end
  return kNoop
end

return { init = init, func = func }
""";
}
